type maintainabilityDiagnostic struct {
	Rule, File, Message, Severity, Fix string
	Line, Column                       int
	Related                            []struct {
		File, Message                    string
		Line, Column, EndLine, EndColumn int
	}
}

func runMaintainability(t *testing.T, args ...string) (int, []maintainabilityDiagnostic, string) {
	t.Helper()
	var stdout, stderr bytes.Buffer
	code := cli.Run(append([]string{"--format=json"}, args...), &stdout, &stderr, maintainability.Plugin)
	var diags []maintainabilityDiagnostic
	if err := json.Unmarshal(stdout.Bytes(), &diags); err != nil {
		t.Fatalf("bad JSON: %v; stdout=%s stderr=%s", err, &stdout, &stderr)
	}
	return code, diags, stderr.String()
}

func TestMaintainabilityCLI(t *testing.T) {
	t.Chdir(t.TempDir())
	writeTestFile(t, "go.mod", "module example.com/maintainability\n\ngo 1.26.0\n")
	writeTestFile(t, ".goxlintrc.json", `{"rules":{
		"maintainability/cyclomatic-complexity":["error",{"max":1}],
		"maintainability/no-duplicate-functions":["warn",{"minStatements":2}]
	}}`)
	writeTestFile(t, "a.go", "package p\nfunc existing(x int) int { if x<0 { return -x }; return x }\n")
	const copySource = "package p\nfunc copied(y int) int { if y<0 { return -y }; return y }\n"
	writeTestFile(t, "b.go", copySource)
	code, diags, stderr := runMaintainability(t, ".")
	if code != 1 || stderr != "" || len(diags) != 3 {
		t.Fatalf("want 3 findings and exit 1, got %d %+v %s", code, diags, stderr)
	}
	complex, duplicates := 0, 0
	for _, d := range diags {
		switch d.Rule {
		case "maintainability/cyclomatic-complexity":
			complex++
			if d.Severity != "error" || !strings.Contains(d.Message, "complexity 2") {
				t.Errorf("bad complexity finding: %+v", d)
			}
		case "maintainability/no-duplicate-functions":
			duplicates++
			if len(d.Related) != 1 {
				t.Fatalf("missing original location: %+v", d)
			}
			ref := d.Related[0]
			if ref.File != "a.go" || ref.Line != 2 || ref.Column != 6 || ref.EndLine != 2 || ref.EndColumn != 14 || ref.Message != "Existing function existing." {
				t.Errorf("wrong original location: %+v", ref)
			}
			if d.File != "b.go" || !strings.Contains(d.Message, "existing at a.go:2:6") || d.Fix != "" {
				t.Errorf("bad duplicate finding: %+v", d)
			}
		default:
			t.Errorf("unexpected diagnostic: %+v", d)
		}
	}
	if complex != 2 || duplicates != 1 {
		t.Fatalf("wrong rule counts: %+v", diags)
	}
	code, diags, _ = runMaintainability(t, "--fix-dangerously", "-A", "maintainability/cyclomatic-complexity", ".")
	if code != 0 || len(diags) != 1 {
		t.Fatalf("rule flag or advisory severity failed: exit %d, %+v", code, diags)
	}
	got, err := os.ReadFile("b.go")
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != copySource {
		t.Fatal("duplicate advisory rewrote source")
	}
}

func TestDuplicateCLILoadingAndOverrides(t *testing.T) {
	t.Chdir(t.TempDir())
	writeTestFile(t, "go.mod", "module example.com/maintainability\n\ngo 1.26.0\n")
	config := `{"rules":{"maintainability/no-duplicate-functions":["warn",{"minStatements":1}]},"ignorePatterns":["ignored.go"]}`
	writeTestFile(t, ".goxlintrc.json", config)
	writeTestFile(t, "a.go", "package p\nfunc existing(x int) int { return x+1 }\n")
	writeTestFile(t, "b.go", "package p\nfunc copied(y int) int { return y+1 }\n")
	writeTestFile(t, "00_generated.go", "// Code generated by a test. DO NOT EDIT.\npackage p\nfunc generated(z int) int { return z+1 }\n")
	writeTestFile(t, "ignored.go", "package p\nfunc ignored(z int) int { return z+1 }\n")
	writeTestFile(t, "z_test.go", "package p\nfunc testHelper(z int) int { return z+1 }\n")
	writeTestFile(t, "z_external_test.go", "package p_test\nfunc externalHelper(z int) int { return z+1 }\n")
	writeTestFile(t, "tagged.go", "//go:build goxlintextra\n\npackage p\nfunc tagged(z int) int { return z+1 }\n")
	if err := os.Mkdir("other", 0o755); err != nil {
		t.Fatal(err)
	}
	writeTestFile(t, "other/c.go", "package p\nfunc separate(z int) int { return z+1 }\n")
	code, diags, stderr := runMaintainability(t, "./...")
	if code != 0 || len(diags) != 1 || diags[0].File != "b.go" || !strings.Contains(diags[0].Message, "a.go:") || stderr != "" {
		t.Fatalf("incorrect package selection: exit %d %+v %s", code, diags, stderr)
	}
	_, diags, _ = runMaintainability(t, "--tags=goxlintextra", "./...")
	if len(diags) != 2 {
		t.Fatalf("build tag did not enable second duplicate: %+v", diags)
	}
	writeTestFile(t, ".goxlintrc.json", strings.TrimSuffix(config, "}")+`,"overrides":[{"files":["b.go"],"rules":{"maintainability/no-duplicate-functions":"off"}}]}`)
	_, diags, _ = runMaintainability(t, "./...")
	if len(diags) != 1 || diags[0].File != "a.go" || !strings.Contains(diags[0].Message, "b.go:") {
		t.Fatalf("disabled file should supply evidence without receiving reports: %+v", diags)
	}
	if len(diags[0].Related) != 1 || diags[0].Related[0].File != "b.go" {
		t.Fatalf("missing disabled reference: %+v", diags)
	}
	writeTestFile(t, ".goxlintrc.json", config)
	writeTestFile(t, "b.go", "package p\n//goxlint:ignore maintainability/no-duplicate-functions required by separate interface\nfunc copied(y int) int { return y+1 }\n")
	code, diags, stderr = runMaintainability(t, "--deny-warnings", "./...")
	if code != 0 || len(diags) != 0 || stderr != "" {
		t.Fatalf("package finding did not consume suppression: exit %d %+v %s", code, diags, stderr)
	}
}

func TestPackageRuleEnabledOnlyByOverride(t *testing.T) {
	t.Chdir(t.TempDir())
	writeTestFile(t, "go.mod", "module example.com/maintainability\n\ngo 1.26.0\n")
	writeTestFile(t, ".goxlintrc.json", `{"overrides":[{"files":["b.go"],"rules":{"maintainability/no-duplicate-functions":["error",{"minStatements":1}]}}]}`)
	writeTestFile(t, "a.go", "package p\nfunc existing(x int) int { return x+1 }\n")
	writeTestFile(t, "b.go", "package p\nfunc copied(y int) int { return y+1 }\n")
	code, diags, stderr := runMaintainability(t, ".")
	if code != 1 || len(diags) != 1 || diags[0].File != "b.go" || diags[0].Severity != "error" || stderr != "" {
		t.Fatalf("override-only package rule failed: exit %d %+v %s", code, diags, stderr)
	}
	writeTestFile(t, "broken.go", "package p\nvar broken int = true\n")
	code, diags, stderr = runMaintainability(t, ".")
	if code != 2 || len(diags) != 0 || !strings.Contains(stderr, "goxlint: load:") {
		t.Fatalf("package rule ran on broken load: exit %d %+v %s", code, diags, stderr)
	}
}

func writeTestFile(t *testing.T, name, source string) {
	t.Helper()
	if err := os.WriteFile(name, []byte(source), 0o644); err != nil {
		t.Fatal(err)
	}
}
